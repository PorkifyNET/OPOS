#!/bin/sh
# Creates the OPOS Store signing key (ECDSA P-256) and writes its public
# half into kernel/store_key.h, which the kernel uses to check the Store
# index (docs/packages.md, "Trust").
#
#   sh tools/store-keygen.sh [KEY_FILE]
#
# KEY_FILE defaults to ~/.opos-signing/store-key.pem. It is separate from
# the update key: losing or leaking one must not affect the other. The
# private key never goes into the repository: anyone who has it can sign
# an index that every OPOS install trusts. Back it up somewhere safe. If
# it is lost, a system update that ships a new kernel/store_key.h
# replaces it.
#
# With an existing KEY_FILE only kernel/store_key.h is (re)written.
set -eu

key=${1:-$HOME/.opos-signing/store-key.pem}
header=$(dirname "$0")/../kernel/store_key.h

if [ ! -f "$key" ]; then
    mkdir -p "$(dirname "$key")"
    chmod 700 "$(dirname "$key")"
    umask 077
    openssl ecparam -name prime256v1 -genkey -noout -out "$key"
    echo "Created $key"
fi

# The DER public key ends with the 65-byte uncompressed point 04||X||Y.
point=$(openssl ec -in "$key" -pubout -outform DER 2>/dev/null \
    | tail -c 65 | od -An -v -tx1 | tr -s ' \n' ' ')

{
    echo "/* Generated by tools/store-keygen.sh: the public key that signs the"
    echo "   OPOS Store index (ECDSA P-256, uncompressed point). Do not edit. */"
    echo "#ifndef OPOS_STORE_KEY_H"
    echo "#define OPOS_STORE_KEY_H"
    echo ""
    echo "#include <stdint.h>"
    echo ""
    echo "static const uint8_t store_public_key[65] = {"
    echo "$point" | tr ' ' '\n' | grep -v '^$' | sed 's/^/0x/' \
        | paste -d, - - - - - - - - - - - - \
        | sed -e 's/,*$//' -e 's/^/    /' -e 's/$/,/'
    echo "};"
    echo ""
    echo "#endif"
} > "$header"
echo "Wrote $header"
