#!/bin/sh
# Creates the OPOS update signing key (ECDSA P-256) and writes its public
# half into kernel/update_key.h, which the kernel uses to check updates.
#
#   sh tools/update-keygen.sh [KEY_FILE]
#
# KEY_FILE defaults to ~/.opos-signing/update-key.pem. The private key
# never goes into the repository: anyone who has it can publish updates
# that every OPOS install accepts. Back it up somewhere safe; if it is
# lost, installs only accept updates signed with a new key after they
# have been reinstalled (or updated by hand) with that key's kernel.
#
# With an existing KEY_FILE only kernel/update_key.h is (re)written.
set -eu

key=${1:-$HOME/.opos-signing/update-key.pem}
header=$(dirname "$0")/../kernel/update_key.h

if [ ! -f "$key" ]; then
    mkdir -p "$(dirname "$key")"
    chmod 700 "$(dirname "$key")"
    umask 077
    openssl ecparam -name prime256v1 -genkey -noout -out "$key"
    echo "Created $key"
fi

# The DER public key ends with the 65-byte uncompressed point 04||X||Y.
point=$(openssl ec -in "$key" -pubout -outform DER 2>/dev/null \
    | tail -c 65 | od -An -v -tx1 | tr -s ' \n' ' ')

{
    echo "/* Generated by tools/update-keygen.sh: the public key that signs OPOS"
    echo "   updates (ECDSA P-256, uncompressed point). Do not edit. */"
    echo "#ifndef OPOS_UPDATE_KEY_H"
    echo "#define OPOS_UPDATE_KEY_H"
    echo ""
    echo "#include <stdint.h>"
    echo ""
    echo "static const uint8_t update_public_key[65] = {"
    echo "$point" | tr ' ' '\n' | grep -v '^$' | sed 's/^/0x/' \
        | paste -d, - - - - - - - - - - - - \
        | sed -e 's/,*$//' -e 's/^/    /' -e 's/$/,/'
    echo "};"
    echo ""
    echo "#endif"
} > "$header"
echo "Wrote $header"
